def plot_results(results, target_baseline):
    gammas = [r["gamma"] for r in results]

    speedups = [
        r["throughput"] / target_baseline["throughput"]
        for r in results
    ]

    acceptance_rates = [r["realized_alpha"] for r in results]

    # ------------------------------------------------------------
    # Plot 1: Speedup vs Gamma
    # ------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    plt.plot(gammas, speedups, marker="o")
    plt.axhline(1.0, linestyle="--", linewidth=1)

    plt.xlabel("Gamma (γ)")
    plt.ylabel("Speedup")
    plt.title("Speculative Decoding Speedup vs Gamma")
    plt.xticks(gammas)
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig("speedup_vs_gamma.png", dpi=200)

    # ------------------------------------------------------------
    # Plot 2: Acceptance Rate vs Gamma
    # ------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    plt.plot(gammas, acceptance_rates, marker="o")

    plt.xlabel("Gamma (γ)")
    plt.ylabel("Realized Acceptance Rate (α)")
    plt.title("Acceptance Rate vs Gamma")
    plt.xticks(gammas)
    plt.ylim(0, 1)
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig("acceptance_rate_vs_gamma.png", dpi=200)

    plt.show()


